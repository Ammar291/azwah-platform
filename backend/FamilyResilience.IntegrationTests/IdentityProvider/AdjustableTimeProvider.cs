namespace FamilyResilience.IntegrationTests.IdentityProvider;

/// <summary>A clock that stands still until a test moves it forward.</summary>
public sealed class AdjustableTimeProvider(DateTimeOffset start) : TimeProvider
{
    private readonly Lock _gate = new();
    private DateTimeOffset _now = start;

    public override DateTimeOffset GetUtcNow()
    {
        lock (_gate)
        {
            return _now;
        }
    }

    public void Advance(TimeSpan by)
    {
        lock (_gate)
        {
            _now += by;
        }
    }
}
